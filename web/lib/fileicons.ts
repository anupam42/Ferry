/** Every icon this module can return, for the generator and its test. */
export const ICON_NAMES = [
  ...new Set([
    ...Object.values(NAMES),
    ...ENDINGS.map(([, i]) => i),
    ...Object.values(EXTS),
    ...Object.values(FOLDERS),
    "folder-base",
    "document",
  ]),
].sort();

/** The icon for a file. "document" when nothing more specific fits. */
export function fileIcon(name: string): string {
  const n = name.toLowerCase();
  if (NAMES[n]) return NAMES[n];
  if (n.startsWith("dockerfile.")) return "docker";
  if (n.startsWith(".env.")) return "tune";
  for (const [end, icon] of ENDINGS) if (n.endsWith(end) && n.length > end.length) return icon;
  const dot = n.lastIndexOf(".");
  return (dot > 0 || (dot === 0 && EXTS[n.slice(1)]) ? EXTS[n.slice(dot + 1)] : undefined) ?? "document";
}

/** The icon for a folder. */
export const folderIcon = (name: string) => FOLDERS[name.toLowerCase()] ?? "folder-base";
