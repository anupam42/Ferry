// Writes the Homebrew formula and the Scoop manifest for a release from
// dist/checksums.txt, and (with --push) commits them to the tap and bucket
// repos. Run by the release workflow after `bun scripts/build.ts --archive`.
//   VERSION=1.3.0 bun scripts/publish-manifests.ts [--push]
// --push needs HOMEBREW_TAP_TOKEN and SCOOP_BUCKET_TOKEN.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const OWNER = "anupam42";
const REPO = `${OWNER}/Ferry`;
const DESC = "Mirror a working folder into a git repo (and back) from any terminal.";
const HOME = `https://github.com/${REPO}`;

process.chdir(path.join(import.meta.dir, ".."));
const version = (process.env.VERSION ?? "").replace(/^v/, "");
if (!version) throw new Error("set VERSION");
const sums = new Map(
  fs
    .readFileSync("dist/checksums.txt", "utf8")
    .trim()
    .split("\n")
    .map((l) => {
      const [h, f] = l.split(/\s+/);
      return [f!, h!] as const;
    }),
);
const asset = (osName: string, arch: string) => {
  const file = `ferry_${version}_${osName}_${arch}.${osName === "windows" ? "zip" : "tar.gz"}`;
  const sha = sums.get(file);
  if (!sha) throw new Error(`${file} missing from dist/checksums.txt`);
  return { url: `${HOME}/releases/download/v${version}/${file}`, sha };
};

const mac = { arm: asset("darwin", "arm64"), intel: asset("darwin", "amd64") };
const linux = { arm: asset("linux", "arm64"), intel: asset("linux", "amd64") };
const formula = `# typed: false
# This file is generated by scripts/publish-manifests.ts in ${REPO}. Do not edit.
class Ferry < Formula
  desc "${DESC}"
  homepage "${HOME}"
  version "${version}"
  license "MIT"

  on_macos do
    if Hardware::CPU.arm?
      url "${mac.arm.url}"
      sha256 "${mac.arm.sha}"
    else
      url "${mac.intel.url}"
      sha256 "${mac.intel.sha}"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "${linux.arm.url}"
      sha256 "${linux.arm.sha}"
    else
      url "${linux.intel.url}"
      sha256 "${linux.intel.sha}"
    end
  end

  def install
    bin.install "ferry"
  end

  test do
    system "#{bin}/ferry", "version"
  end
end
`;

const win = { x64: asset("windows", "amd64"), arm: asset("windows", "arm64") };
const scoop = {
  version,
  description: DESC,
  homepage: HOME,
  license: "MIT",
  architecture: {
    "64bit": { url: win.x64.url, hash: win.x64.sha },
    arm64: { url: win.arm.url, hash: win.arm.sha },
  },
  bin: "ferry.exe",
  checkver: { github: HOME },
  autoupdate: {
    architecture: {
      "64bit": { url: `${HOME}/releases/download/v$version/ferry_$version_windows_amd64.zip` },
      arm64: { url: `${HOME}/releases/download/v$version/ferry_$version_windows_arm64.zip` },
    },
    hash: { url: `${HOME}/releases/download/v$version/checksums.txt` },
  },
};

fs.writeFileSync("dist/ferry.rb", formula);
fs.writeFileSync("dist/ferry.json", JSON.stringify(scoop, null, 2) + "\n");
console.log("wrote dist/ferry.rb and dist/ferry.json");

if (!process.argv.includes("--push")) process.exit(0);

async function git(cwd: string, ...args: string[]): Promise<void> {
  const p = Bun.spawn({ cmd: ["git", ...args], cwd, stdout: "inherit", stderr: "inherit" });
  if ((await p.exited) !== 0) throw new Error(`git ${args[0]} failed`);
}

async function publish(repo: string, token: string | undefined, file: string, dest: string): Promise<void> {
  if (!token) {
    console.log(`skipping ${repo}: no token`);
    return;
  }
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "ferry-publish-"));
  await git(dir, "clone", "--depth", "1", `https://x-access-token:${token}@github.com/${OWNER}/${repo}.git`, ".");
  fs.mkdirSync(path.dirname(path.join(dir, dest)), { recursive: true });
  fs.copyFileSync(file, path.join(dir, dest));
  await git(dir, "add", "--", dest);
  await git(
    dir,
    "-c",
    "user.name=ferry-release",
    "-c",
    "user.email=ferry-release@users.noreply.github.com",
    "commit",
    "-m",
    `ferry ${version}`,
    "--allow-empty",
  );
  await git(dir, "push");
  console.log(`updated ${OWNER}/${repo}/${dest}`);
}

await publish("homebrew-tap", process.env.HOMEBREW_TAP_TOKEN, "dist/ferry.rb", "Formula/ferry.rb");
await publish("scoop-bucket", process.env.SCOOP_BUCKET_TOKEN, "dist/ferry.json", "ferry.json");
